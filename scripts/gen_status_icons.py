#!/usr/bin/env python3
"""Share the existing Lucide icon alpha masks between PocketJS and Web previews."""
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
SIZE = 28
ICONS = {"eth": "net", "hdmi": "hdmi", "hid": "usb", "wifi": "wifi", "live": "stream"}

lines = ["// Generated by scripts/gen_status_icons.py from the shared Lucide PNG assets.",
         "// 28 × 28 square alpha masks; 4-bit coverage keeps native and Web edges identical.",
         "export const STATUS_ICON_SIZE = 28", "export const statusIconMasks = {"]
for source, asset in ICONS.items():
    alpha = Image.open(ROOT / "src" / f"{asset}.png").convert("RGBA").getchannel("A")
    alpha = alpha.resize((SIZE, SIZE), Image.Resampling.LANCZOS)
    rows = ["".join(format(round(alpha.getpixel((x, y)) / 17), "x") for x in range(SIZE)) for y in range(SIZE)]
    lines.append(f"  {source}: [")
    lines.extend(f"    '{row}'," for row in rows)
    lines.append("  ],")
lines.append("} as const")
(ROOT / "src/shared/statusIconMasks.ts").write_text("\n".join(lines) + "\n")
